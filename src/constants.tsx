export function buildExecutiveSummary(lang: string, parts: {
  name?: string; country?: string; caseType?: string; entryDate?: string;
  residenceCountry: string; zip?: string; city?: string;
}): string {
  const s = EXEC_SUMMARY_I18N[lang] || EXEC_SUMMARY_I18N.EN;
  const caseType = parts.caseType === 'asylum' ? s.caseTypes.asylum
    : parts.caseType === 'family' ? s.caseTypes.family : s.caseTypes.other;
  const entry = parts.entryDate ? s.entryKnown(parts.entryDate) : s.entryUnknown;
  const residence = parts.residenceCountry === 'US'
    ? s.residenceUs(parts.zip || s.zipUnspecified)
    : s.residenceIntl(`${parts.city ? parts.city + ', ' : ''}${parts.residenceCountry}`);
  return s.assemble({
    name: parts.name || s.applicantDefault,
    country: parts.country || s.countryDefault,
    entry, caseType, residence,
  });
}
